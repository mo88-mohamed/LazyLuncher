using System.Diagnostics;
using System.Text;
using System.Xml.Linq;

namespace LaunchForge.Core;

public enum ExportFormat { WindowsBatch, LinuxShell, WindowsExecutable, LinuxExecutable }

public static class LauncherExporter
{
    private static string ShellQuote(string text) => "'" + text.Replace("'", "'\"'\"'") + "'";
    private static string PowerShellQuote(string text) => "'" + text.Replace("'", "''") + "'";

    public static string CreateShell(Workflow workflow)
    {
        workflow.Validate(windows: false);
        var result = new StringBuilder("#!/usr/bin/env bash\nset -e\n# Generated by LaunchForge. Commands run with your user permissions.\n");
        foreach (var step in workflow.Steps)
        {
            var folder = string.IsNullOrWhiteSpace(step.WorkingDirectory) ? workflow.WorkingDirectory : step.WorkingDirectory;
            result.AppendLine($"printf '%s\\n' {ShellQuote("Starting: " + step.Name)}");
            result.AppendLine($"(cd -- {ShellQuote(folder)} && bash -c {ShellQuote(step.LinuxCommand)}){(step.WaitForExit ? "" : " &")}");
        }
        return result.ToString().Replace("\r\n", "\n");
    }

    public static string CreateBatch(Workflow workflow)
    {
        workflow.Validate(windows: true);
        // Encoding keeps cmd metacharacters in folder names and commands out of the outer batch parser.
        var script = new StringBuilder("$ErrorActionPreference = 'Stop'\n$ProgressPreference = 'SilentlyContinue'\ntry {\n");
        foreach (var step in workflow.Steps)
        {
            var folder = string.IsNullOrWhiteSpace(step.WorkingDirectory) ? workflow.WorkingDirectory : step.WorkingDirectory;
            script.AppendLine($"[Console]::WriteLine({PowerShellQuote("Starting: " + step.Name)})");
            script.AppendLine($"if (-not (Test-Path -LiteralPath {PowerShellQuote(folder)} -PathType Container)) {{ throw 'Working folder does not exist.' }}");
            script.AppendLine("$info = New-Object System.Diagnostics.ProcessStartInfo");
            script.AppendLine("$info.FileName = 'cmd.exe'");
            script.AppendLine("$info.UseShellExecute = $false");
            script.AppendLine($"$info.WorkingDirectory = {PowerShellQuote(folder)}");
            script.AppendLine($"$info.Arguments = {PowerShellQuote("/d /s /c \"" + step.WindowsCommand + "\"")}");
            script.AppendLine("$process = [System.Diagnostics.Process]::Start($info)");
            if (step.WaitForExit) script.AppendLine("$process.WaitForExit(); if ($process.ExitCode -ne 0) { exit $process.ExitCode }");
            script.AppendLine("$process.Dispose()");
        }
        script.AppendLine("exit 0\n} catch { [Console]::Error.WriteLine($_.Exception.Message); exit 1 }");
        var encoded = Convert.ToBase64String(Encoding.Unicode.GetBytes(script.ToString()));
        // cmd.exe has an 8191-character line limit.
        if (encoded.Length > 7800) throw new InvalidDataException("This workflow is too large for a batch launcher. Export an executable instead.");
        return "@echo off\r\npowershell.exe -NoLogo -NoProfile -OutputFormat Text -ExecutionPolicy Bypass -EncodedCommand " + encoded + "\r\nexit /b %errorlevel%\r\n";
    }

    public static async Task ExportAsync(Workflow workflow, ExportFormat format, string destination, Action<string>? log = null, CancellationToken cancellationToken = default)
    {
        if (format is ExportFormat.WindowsBatch or ExportFormat.LinuxShell)
        {
            var content = format == ExportFormat.WindowsBatch ? CreateBatch(workflow) : CreateShell(workflow);
            await File.WriteAllTextAsync(destination, content, new UTF8Encoding(false), cancellationToken);
            if (format == ExportFormat.LinuxShell && !OperatingSystem.IsWindows())
                File.SetUnixFileMode(destination, UnixFileMode.UserRead | UnixFileMode.UserWrite | UnixFileMode.UserExecute | UnixFileMode.GroupRead | UnixFileMode.GroupExecute | UnixFileMode.OtherRead | UnixFileMode.OtherExecute);
            return;
        }
        bool windows = format == ExportFormat.WindowsExecutable;
        workflow.Validate(windows);
        string scratch = Path.Combine(Path.GetTempPath(), "LaunchForge", Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(scratch);
        try
        {
            await File.WriteAllTextAsync(Path.Combine(scratch, "workflow.json"), workflow.ToJson(), cancellationToken);
            foreach (string source in new[] { "Workflow.cs", "WorkflowRunner.cs" })
            {
                using var stream = typeof(LauncherExporter).Assembly.GetManifestResourceStream(source)!;
                using var reader = new StreamReader(stream);
                await File.WriteAllTextAsync(Path.Combine(scratch, source), await reader.ReadToEndAsync(cancellationToken), cancellationToken);
            }
            await File.WriteAllTextAsync(Path.Combine(scratch, "Program.cs"), """
                using LaunchForge.Core;
                using System.Reflection;
                try
                {
                    using var stream = Assembly.GetExecutingAssembly().GetManifestResourceStream("workflow.json")!;
                    using var reader = new StreamReader(stream);
                    return await WorkflowRunner.RunAsync(Workflow.FromJson(await reader.ReadToEndAsync()), Console.WriteLine);
                }
                catch (Exception exception) { Console.Error.WriteLine(exception.Message); return 1; }
                """, cancellationToken);
            var project = new XDocument(new XElement("Project", new XAttribute("Sdk", "Microsoft.NET.Sdk"),
                new XElement("PropertyGroup",
                    new XElement("OutputType", "Exe"), new XElement("TargetFramework", "net10.0"),
                    new XElement("ImplicitUsings", "enable"), new XElement("Nullable", "enable"),
                    new XElement("AssemblyName", "Launcher"), new XElement("PublishSingleFile", "true"),
                    new XElement("DisableTransitiveFrameworkReferenceDownloads", "true"),
                    new XElement("IncludeNativeLibrariesForSelfExtract", "true")),
                new XElement("ItemGroup", new XElement("EmbeddedResource", new XAttribute("Include", "workflow.json"), new XAttribute("LogicalName", "workflow.json")))));
            project.Save(Path.Combine(scratch, "Launcher.csproj"));
            var start = new ProcessStartInfo("dotnet") { WorkingDirectory = scratch, UseShellExecute = false, RedirectStandardOutput = true, RedirectStandardError = true, CreateNoWindow = true };
            foreach (string argument in new[] { "publish", "Launcher.csproj", "-c", "Release", "-r", windows ? "win-x64" : "linux-x64", "--self-contained", "true", "-o", "publish" }) start.ArgumentList.Add(argument);
            log?.Invoke("Building a standalone launcher. First export may download the .NET runtime.");
            using var process = Process.Start(start) ?? throw new IOException("Install the .NET 10 SDK to export executables.");
            var stdout = process.StandardOutput.ReadToEndAsync(cancellationToken);
            var stderr = process.StandardError.ReadToEndAsync(cancellationToken);
            try { await process.WaitForExitAsync(cancellationToken); }
            catch (OperationCanceledException) { if (!process.HasExited) process.Kill(true); throw; }
            var output = await stdout;
            var errors = await stderr;
            if (process.ExitCode != 0) throw new IOException("Executable export failed:\n" + output + errors);
            var binary = Path.Combine(scratch, "publish", windows ? "Launcher.exe" : "Launcher");
            File.Copy(binary, destination, overwrite: true);
            if (!windows && !OperatingSystem.IsWindows()) File.SetUnixFileMode(destination, UnixFileMode.UserRead | UnixFileMode.UserWrite | UnixFileMode.UserExecute | UnixFileMode.GroupRead | UnixFileMode.GroupExecute | UnixFileMode.OtherRead | UnixFileMode.OtherExecute);
        }
        finally { try { Directory.Delete(scratch, recursive: true); } catch (IOException) { } catch (UnauthorizedAccessException) { } }
    }
}
